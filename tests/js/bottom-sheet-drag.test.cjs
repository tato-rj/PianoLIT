const assert = require('node:assert/strict');
const test = require('node:test');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');

function setup(height = 500) {
    const element = () => ({
        events: {}, classes: new Set(), properties: {},
        attributes: { 'data-bs-dismiss': 'offcanvas' },
        removeAttribute(name) { delete this.attributes[name]; },
        addEventListener(name, fn) { (this.events[name] ||= []).push(fn); },
        fire(name, event = {}) { this.events[name]?.forEach(fn => fn(event)); },
        getBoundingClientRect: () => ({ height }),
        setPointerCapture(id) { this.capture = id; },
        hasPointerCapture(id) { return id === this.capture; },
        releasePointerCapture(id) { this.capture = null; this.fire('lostpointercapture', { pointerId: id }); },
    });
    const panel = element(), handle = element(), window = element(), document = element();
    panel.classList = { contains: name => panel.classes.has(name), add: name => panel.classes.add(name), remove: name => panel.classes.delete(name) };
    panel.style = { setProperty: (name, value) => panel.properties[name] = value, removeProperty: name => delete panel.properties[name] };
    panel.querySelector = () => handle;
    panel.classes.add('show');
    const context = vm.createContext({ window, document });
    const source = fs.readFileSync(path.resolve(__dirname, '../../resources/js/controls/bottom-sheet-drag.js'), 'utf8').replace(/^export /gm, '');
    vm.runInContext(source + '\nglobalThis.BottomSheetDrag = BottomSheetDrag;', context);
    let closed = 0;
    const drag = new context.BottomSheetDrag(panel, () => { closed++; panel.fire('hide.bs.offcanvas'); panel.classes.add('hiding'); });
    const event = (y, time = 0, extra = {}) => ({ isPrimary: true, button: 0, pointerId: 1, clientX: 400, clientY: y, timeStamp: time,
        preventDefault() { this.prevented = true; }, stopPropagation() { this.stopped = true; }, ...extra });
    return { panel, handle, window, document, drag, event, get closed() { return closed; } };
}

test('a downward drag follows the pointer and dismisses through the normal lifecycle', () => {
    const page = setup();
    page.handle.fire('pointerdown', page.event(50));
    page.handle.fire('pointermove', page.event(180, 300));
    assert.equal(page.panel.properties['--bottom-sheet-drag-y'], '130px');
    assert.equal(page.handle.capture, 1);
    page.handle.fire('pointerup', page.event(180, 450));
    assert.equal(page.closed, 1);
    assert.equal(page.panel.properties['--bottom-sheet-drag-y'], '130px', 'Bootstrap continues from the dragged position');
    assert.equal(page.handle.capture, null);
    page.panel.fire('hidden.bs.offcanvas');
    assert.equal(page.panel.properties['--bottom-sheet-drag-y'], undefined);
    const click = page.event(180, 460, { detail: 1 });
    page.handle.fire('click', click);
    assert.equal(click.prevented, true);
    assert.equal(click.stopped, true);
});

test('a short pull snaps back, while a deliberate quick downward flick closes', () => {
    const page = setup();
    page.handle.fire('pointerdown', page.event(0));
    page.handle.fire('pointermove', page.event(40, 200));
    page.handle.fire('pointerup', page.event(40, 350));
    assert.equal(page.closed, 0);
    assert.equal(page.panel.properties['--bottom-sheet-drag-y'], undefined);
    assert.equal(page.handle.attributes['data-bs-dismiss'], undefined, 'delegated capture must not dismiss before click suppression');
    page.handle.fire('click', page.event(40, 360, { detail: 1 }));
    assert.equal(page.closed, 0, 'the click generated by a short drag must not dismiss');
    page.handle.fire('pointerdown', page.event(0, 400));
    page.handle.fire('pointermove', page.event(50, 450));
    page.handle.fire('pointerup', page.event(50, 460));
    assert.equal(page.closed, 1);
});

test('upward and sideways gestures never dismiss or become accidental clicks', () => {
    for (const end of [{ clientY: -180 }, { clientY: 40, clientX: 600 }]) {
        const page = setup();
        page.handle.fire('pointerdown', page.event(0));
        page.handle.fire('pointermove', page.event(0, 100, end));
        page.handle.fire('pointerup', page.event(0, 200, end));
        assert.equal(page.closed, 0);
        const click = page.event(0, 210, { detail: 1 }); page.handle.fire('click', click);
        assert.equal(click.prevented, true);
    }
});

test('handle taps and keyboard activation retain Bootstrap dismissal', () => {
    const page = setup();
    page.handle.fire('pointerdown', page.event(0));
    page.handle.fire('pointerup', page.event(2, 80));
    const click = page.event(2, 90, { detail: 1 }); page.handle.fire('click', click);
    assert.equal(click.prevented, undefined);
    assert.equal(page.closed, 1);
    page.panel.classes.delete('hiding');
    page.drag.suppressClick = true;
    const keyboard = page.event(0, 100, { detail: 0 }); page.handle.fire('click', keyboard);
    assert.equal(keyboard.prevented, undefined);
    assert.equal(page.closed, 2);
});

test('pointer interruption, resize, blur and hidden pages cancel without dismissing', () => {
    for (const reason of ['pointercancel', 'lostpointercapture', 'resize', 'blur', 'visibilitychange']) {
        const page = setup();
        page.handle.fire('pointerdown', page.event(0));
        page.handle.fire('pointermove', page.event(140, 200));
        if (reason === 'visibilitychange') { page.document.hidden = true; page.document.fire(reason); }
        else if (['resize', 'blur'].includes(reason)) page.window.fire(reason);
        else page.handle.fire(reason, page.event(140, 220));
        assert.equal(page.closed, 0, reason);
        assert.equal(page.drag.gesture, null, reason);
        assert.equal(page.panel.properties['--bottom-sheet-drag-y'], undefined, reason);
    }
});

test('ignore secondary pointers and opening/closing transitions', () => {
    const page = setup();
    for (const className of ['showing', 'hiding']) {
        page.panel.classes.add(className);
        page.handle.fire('pointerdown', page.event(0));
        assert.equal(page.drag.gesture, null);
        page.panel.classes.delete(className);
    }
    page.handle.fire('pointerdown', page.event(0, 0, { isPrimary: false }));
    assert.equal(page.drag.gesture, null);
    page.handle.fire('pointerdown', page.event(0));
    page.handle.fire('pointercancel', page.event(140, 100, { pointerId: 2 }));
    page.handle.fire('pointermove', page.event(140, 100, { pointerId: 2 }));
    assert.equal(page.panel.properties['--bottom-sheet-drag-y'], undefined);
    assert.equal(page.drag.gesture.id, 1);
    page.panel.fire('hide.bs.offcanvas');
    assert.equal(page.drag.gesture, null);
    page.panel.fire('hidden.bs.offcanvas');
    page.panel.fire('show.bs.offcanvas');
    assert.equal(page.panel.properties['--bottom-sheet-drag-y'], undefined);
});
